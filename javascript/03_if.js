// 03 if / else

const age = 20;

if (age >= 18) {
  console.log("adult");
} else {
  console.log("not adult yet");
}

// else if
const score = 85;

if (score >= 90) {
  console.log("A");
} else if (score >= 80) {
  console.log("B");
} else if (score >= 70) {
  console.log("C");
} else {
  console.log("need more work");
}
